import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync('src/lib/prompt-composer.ts', 'utf8');
const output = '// Generated by scripts/build-composer.mjs. Edit src/lib/prompt-composer.ts.\n' + ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: false } }).outputText;
if (process.argv.includes('--check')) {
  if (readFileSync('extension/composer.js', 'utf8') !== output) throw new Error('Extension composer is stale. Run npm run build:composer.');
} else writeFileSync('extension/composer.js', output);
